// Explicit, scoped integration of the three user-approved v1 proposals.
// Run --prepare to create backups, overrides and update only approved atlas pixels.
// Run --record after code changes to record hashes used by guarded rollback.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {PNG} from 'pngjs';
import {writePng} from '../scripts/png.js';
const root=path.resolve(import.meta.dirname,'..');
const backup=path.join(import.meta.dirname,'backups','approved-v1');
const targets=['src/art/bakedBuildings.js','src/art/bakedNature.js','scripts/generate-assets.js','public/assets/buildings/camp-atlas.png','public/assets/nature/nature-atlas.png'];
const added=['src/art/approvedBuildingSprites.js','src/art/approvedNatureSprites.js'];
const hash=data=>createHash('sha256').update(data).digest('hex');
const manifestFile=path.join(backup,'manifest.json');
function encode(p){
  const colors=['00000000'],indices=new Map([['00000000',0]]),runs=[];let last=-1,count=0;
  for(let i=0;i<p.data.length;i+=4){const c=p.data[i+3]?p.data.subarray(i,i+4).toString('hex'):'00000000';if(!indices.has(c)){indices.set(c,colors.length);colors.push(c);}const index=indices.get(c);if(index===last&&count<255)count++;else{if(count)runs.push(last,count);last=index;count=1;}}
  if(count)runs.push(last,count);
  return {w:p.width,h:p.height,frames:1,colors:colors.join(','),data:Buffer.from(runs).toString('base64')};
}
function crop(p,x,y,w,h){const out=new PNG({width:w,height:h});PNG.bitblt(p,out,x,y,w,h,0,0);return out;}
if(process.argv.includes('--prepare')){
  if(fs.existsSync(manifestFile))throw Error('Backup already exists; do not overwrite an integration snapshot');
  const decisions=JSON.parse(fs.readFileSync(path.join(import.meta.dirname,'approvals.json'))).history;
  const ids=['tower-stone','forge','vegetation'];
  for(const id of ids)if(decisions.filter(d=>d.id===id&&d.version==='v1').at(-1)?.status!=='approved')throw Error(`${id} v1 not approved`);
  const proposals=Object.fromEntries(ids.map(id=>[id,PNG.sync.read(fs.readFileSync(path.join(import.meta.dirname,`proposals/${id}/v1/proposed.png`)))]));
  for(const [id,w,h]of [['tower-stone',90,174],['forge',168,176],['vegetation',132,88]])if(proposals[id].width!==w||proposals[id].height!==h)throw Error(`Unexpected ${id} dimensions`);
  if(added.some(file=>fs.existsSync(path.join(root,file))))throw Error('Override files already exist');
  const files=targets.map(file=>{const data=fs.readFileSync(path.join(root,file));const to=path.join(backup,file);fs.mkdirSync(path.dirname(to),{recursive:true});fs.writeFileSync(to,data,{flag:'wx'});return {file,before:hash(data)};});
  const manifest={date:new Date().toISOString(),authorization:'User: integre e envie ao github; three v1 approvals in panel',files,added,proposals:ids.map(id=>({id,version:'v1',sha256:hash(fs.readFileSync(path.join(import.meta.dirname,`proposals/${id}/v1/proposed.png`)))}))};
  fs.writeFileSync(manifestFile,JSON.stringify(manifest,null,2)+'\n',{flag:'wx'});
  const v=proposals.vegetation;
  const nature={'oak-tree':crop(v,0,0,72,88),bush:crop(v,72,58,40,30),'detail-flowers':crop(v,112,72,20,16)};
  for(const [file,name,entries]of [[added[0],'APPROVED_BUILDINGS',{'tower-stone':proposals['tower-stone'],forge:proposals.forge}],[added[1],'APPROVED_NATURE',nature]]){
    fs.writeFileSync(path.join(root,file),`// Approved v1 art. Generated by art-review/integrate-approved.mjs; do not hand-edit RLE.\nexport const ${name} = ${JSON.stringify(Object.fromEntries(Object.entries(entries).map(([k,p])=>[k,encode(p)]))).replace(/\},"/g,'},\n"')};\n`,{flag:'wx'});
  }
  for(const [atlas,entries]of [['buildings/camp',{forge:proposals.forge}],['nature/nature',nature]]){
    const base=path.join(root,`public/assets/${atlas}-atlas`);const p=PNG.sync.read(fs.readFileSync(`${base}.png`));const meta=JSON.parse(fs.readFileSync(`${base}.json`));
    for(const [name,sprite]of Object.entries(entries)){const f=meta.frames[name].frame;if(f.w!==sprite.width||f.h!==sprite.height)throw Error(`Frame mismatch ${name}`);PNG.bitblt(sprite,p,0,0,f.w,f.h,f.x,f.y);}
    writePng(`${base}.png`,p,{quantize:false});
  }
  console.log('Backed up original files; exact approved frames and override data written.');
}else if(process.argv.includes('--record')){
  const manifest=JSON.parse(fs.readFileSync(manifestFile));
  for(const f of manifest.files)f.after=hash(fs.readFileSync(path.join(root,f.file)));
  manifest.added=manifest.added.map(f=>typeof f==='string'?{file:f,after:hash(fs.readFileSync(path.join(root,f)))}:f);
  fs.writeFileSync(manifestFile,JSON.stringify(manifest,null,2)+'\n');console.log('Integration hashes recorded.');
}else throw Error('Use --prepare or --record explicitly');
